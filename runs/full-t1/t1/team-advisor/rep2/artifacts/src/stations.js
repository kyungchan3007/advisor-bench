  '을지로': { '동대문': 2.8, '왕십리': 7.1, '성수': 10.0 },
  '동대문': { '성수': 7.2, '건대': 9.9, '청량리': 4.4 },
  '성수': { '건대': 2.7, '잠실': 8.6 },
  '건대': { '잠실': 5.9, '천호': 7.7 },
